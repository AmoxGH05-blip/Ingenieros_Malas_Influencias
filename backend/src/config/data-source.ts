import "reflect-metadata";
import { DataSource } from "typeorm";
import {
  Rol,
  Usuario,
  Facultad,
  ProgramaEducativo,
  Docente,
  Estudiante,
  Materia,
  Grupo,
  PeriodoAcademico,
  Inscripcion,
  UsuarioRol,
  Sesion,
  SolicitudCambioPassword,
  TipoPregunta,
  InstrumentoEvaluacion,
  SeccionInstrumento,
  Pregunta,
  OpcionRespuesta,
  PeriodoEvaluacion,
  Evaluacion,
  RespuestaEvaluacion,
} from "../entities";

export const AppDataSource = new DataSource({
  type: "postgres",
  host: process.env.DB_HOST,
  port: Number(process.env.DB_PORT ?? 5432),
  database: process.env.DB_NAME,
  username: process.env.DB_USER,
  password: process.env.DB_PASSWORD,
  ssl: (process.env.DB_SSL ?? "true") === "true" ? { rejectUnauthorized: false } : false,
  synchronize: false,
  logging: false,
  // Opciones del pool de pg. Supabase limita las conexiones, y cada llamada de estadisticas lanza 4 consultas en paralelo:
  // un tope explicito evita agotarlas, y el timeout hace fallar rapido en vez de colgar la peticion.
  extra: {
    max: Number(process.env.DB_POOL_MAX ?? 10),
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 10_000,
  },
  entities: [
    Rol,
    Usuario,
    Facultad,
    ProgramaEducativo,
    Docente,
    Estudiante,
    Materia,
    Grupo,
    PeriodoAcademico,
    Inscripcion,
    UsuarioRol,
    Sesion,
    SolicitudCambioPassword,
    TipoPregunta,
    InstrumentoEvaluacion,
    SeccionInstrumento,
    Pregunta,
    OpcionRespuesta,
    PeriodoEvaluacion,
    Evaluacion,
    RespuestaEvaluacion,
  ],
});
